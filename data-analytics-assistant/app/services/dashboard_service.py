"""
Dashboard Service
Utilities for post-processing, validating, enriching, and exporting
Power BI Dashboard Specifications generated by the PowerBI Builder Agent.
"""
from __future__ import annotations

import json
from typing import Any, Optional

from app.schemas.dashboard import DashboardSpec, DashboardPage, Visual, KPICard
from app.schemas.kpi import KPI
from app.schemas.insight import Insight


class DashboardService:
    """
    Post-processing layer for DashboardSpec objects.
    Provides enrichment, validation, format conversion, and export helpers.
    """

    # ── Validation ────────────────────────────────────────────────────────────

    def validate_spec(self, spec: DashboardSpec) -> list[str]:
        """
        Validate a DashboardSpec for completeness and coherence.
        Returns a list of warning messages (empty = valid).
        """
        warnings: list[str] = []

        if not spec.title:
            warnings.append("Dashboard title is missing.")
        if not spec.pages:
            warnings.append("Dashboard has no pages defined.")
        for page in spec.pages:
            if not page.visuals and not page.kpi_cards:
                warnings.append(f"Page '{page.page_name}' has no visuals or KPI cards.")
            for v in page.visuals:
                if not v.chart_type:
                    warnings.append(f"Visual '{v.title}' on page '{page.page_name}' has no chart type.")
        return warnings

    # ── Enrichment ────────────────────────────────────────────────────────────

    def enrich_with_kpis(
        self,
        spec: DashboardSpec,
        kpis: list[KPI],
        target_page_index: int = 0,
    ) -> DashboardSpec:
        """
        Inject KPI card definitions from the KPI list into a target page.
        Useful when the LLM didn't produce well-structured KPI cards.
        """
        if not spec.pages or target_page_index >= len(spec.pages):
            return spec

        page = spec.pages[target_page_index]
        existing_names = {c.title.lower() for c in page.kpi_cards}

        position_row = len(page.kpi_cards) + 1
        for i, kpi in enumerate(kpis[:8]):  # cap at 8 cards per page
            if kpi.name.lower() not in existing_names:
                card = KPICard(
                    title=kpi.name,
                    measure=kpi.required_columns[0] if kpi.required_columns else kpi.name,
                    format=_infer_format(kpi.unit),
                    comparison="vs previous period",
                    position={"row": position_row, "col": (i % 4) + 1, "width": 2, "height": 1},
                )
                page.kpi_cards.append(card)
        return spec

    def enrich_with_insights(
        self,
        spec: DashboardSpec,
        insights: list[Insight],
        target_page_index: int = 0,
    ) -> DashboardSpec:
        """
        Add a text/table visual for each critical or high-priority insight
        on the target page.
        """
        if not spec.pages or target_page_index >= len(spec.pages):
            return spec

        page = spec.pages[target_page_index]
        critical_insights = [i for i in insights if i.priority in ("Critical", "High")]

        for idx, insight in enumerate(critical_insights[:4]):
            visual_id = f"insight_visual_{idx + 1}"
            existing_ids = {v.id for v in page.visuals}
            if visual_id not in existing_ids:
                visual = Visual(
                    id=visual_id,
                    title=f"⚠️ {insight.title}",
                    chart_type="card",
                    measures=[],
                    dimensions=[],
                    business_purpose=insight.executive_summary,
                    position={"row": 10 + idx, "col": 1, "width": 6, "height": 2},
                )
                page.visuals.append(visual)
        return spec

    # ── Export / Format Conversion ────────────────────────────────────────────

    def to_json(self, spec: DashboardSpec, indent: int = 2) -> str:
        """Serialize the full DashboardSpec to a pretty-printed JSON string."""
        raw = spec.raw_spec if spec.raw_spec else spec.model_dump(exclude={"raw_spec"})
        return json.dumps(raw, indent=indent, ensure_ascii=False)

    def to_powerbi_template(self, spec: DashboardSpec) -> dict[str, Any]:
        """
        Convert a DashboardSpec to a Power BI Report Builder-compatible
        JSON template structure.

        This is an approximation; actual PBIX automation requires the
        Power BI REST API or Tabular Editor scripting.
        """
        template: dict[str, Any] = {
            "version": "1.0",
            "reportTemplate": {
                "id": f"report_{spec.title.lower().replace(' ', '_')}",
                "displayName": spec.title,
                "description": spec.description,
                "targetAudience": spec.target_audience,
                "refreshSchedule": spec.data_refresh_frequency,
                "globalFilters": spec.global_filters,
                "pages": [],
            }
        }

        for page in spec.pages:
            page_obj: dict[str, Any] = {
                "name": page.page_name,
                "displayName": page.page_name,
                "order": page.page_number,
                "purpose": page.purpose,
                "theme": page.theme,
                "slicers": [
                    {"column": s, "type": "DropDown"} for s in page.slicers
                ],
                "visuals": [],
            }

            # KPI cards → Card visuals
            for card in page.kpi_cards:
                page_obj["visuals"].append({
                    "type": "cardVisual",
                    "title": card.title,
                    "measure": card.measure,
                    "format": card.format,
                    "comparison": card.comparison,
                    "layout": card.position,
                })

            # Regular visuals
            for v in page.visuals:
                page_obj["visuals"].append({
                    "type": v.chart_type,
                    "id": v.id,
                    "title": v.title,
                    "xAxis": v.x_axis,
                    "yAxis": v.y_axis,
                    "legend": v.legend,
                    "measures": v.measures,
                    "dimensions": v.dimensions,
                    "filters": v.filters,
                    "drillDown": v.drill_down,
                    "layout": v.position,
                    "businessPurpose": v.business_purpose,
                })

            template["reportTemplate"]["pages"].append(page_obj)

        return template

    def to_markdown_summary(self, spec: DashboardSpec) -> str:
        """Generate a Markdown summary of the dashboard specification."""
        lines = [
            f"## {spec.title}",
            f"*{spec.description}*",
            f"",
            f"**Audience:** {spec.target_audience} | **Refresh:** {spec.data_refresh_frequency}",
            f"",
        ]
        if spec.executive_summary:
            lines += [spec.executive_summary, ""]

        for page in spec.pages:
            lines += [
                f"### Page {page.page_number}: {page.page_name}",
                f"_{page.purpose}_",
                f"",
            ]
            if page.kpi_cards:
                lines.append(f"**KPI Cards:** {', '.join(c.title for c in page.kpi_cards)}")
            if page.slicers:
                lines.append(f"**Slicers:** {', '.join(page.slicers)}")
            if page.visuals:
                lines.append(f"**Visuals:** {', '.join(v.title for v in page.visuals)}")
            lines.append("")

        if spec.implementation_notes:
            lines += ["**Implementation Notes:**", ""]
            for note in spec.implementation_notes:
                lines.append(f"- {note}")

        return "\n".join(lines)

    # ── Page-level utilities ──────────────────────────────────────────────────

    def get_page_by_name(self, spec: DashboardSpec, name: str) -> Optional[DashboardPage]:
        for page in spec.pages:
            if page.page_name.lower() == name.lower():
                return page
        return None

    def count_total_visuals(self, spec: DashboardSpec) -> int:
        return sum(len(p.visuals) + len(p.kpi_cards) for p in spec.pages)

    def get_all_measures(self, spec: DashboardSpec) -> list[str]:
        measures: list[str] = []
        for page in spec.pages:
            for card in page.kpi_cards:
                measures.append(card.measure)
            for v in page.visuals:
                measures.extend(v.measures)
        return list(dict.fromkeys(measures))  # deduplicated, order-preserved

    def get_all_dimensions(self, spec: DashboardSpec) -> list[str]:
        dims: list[str] = []
        for page in spec.pages:
            for v in page.visuals:
                dims.extend(v.dimensions)
                if v.x_axis:
                    dims.append(v.x_axis)
        return list(dict.fromkeys(dims))


# ── Helpers ───────────────────────────────────────────────────────────────────

def _infer_format(unit: Optional[str]) -> str:
    if not unit:
        return "number"
    u = unit.lower()
    if "$" in u or "usd" in u or "revenue" in u or "cost" in u or "price" in u:
        return "currency"
    if "%" in u or "rate" in u or "pct" in u or "percent" in u:
        return "percentage"
    if "." in u or "ratio" in u:
        return "decimal"
    return "number"


# ── Singleton ─────────────────────────────────────────────────────────────────

_dashboard_service: Optional[DashboardService] = None


def get_dashboard_service() -> DashboardService:
    global _dashboard_service
    if _dashboard_service is None:
        _dashboard_service = DashboardService()
    return _dashboard_service
